"""
Модуль для безопасного хеширования и проверки паролей с использованием bcrypt.

Назначение:
    Предоставляет функции для создания хешей паролей и их верификации
    с использованием адаптивного алгоритма bcrypt.

Основные функции:
    - get_password_hash(): создаёт криптографически безопасный хеш пароля
    - verify_password(): проверяет соответствие открытого пароля хешу

Ключевые особенности:
    - Автоматическая генерация случайной соли для каждого пароля
    - Адаптивная сложность вычислений (защита от перебора)
    - Обработка краевых случаев (None, пустые строки, невалидные данные)
    - Безопасное возвращение False при любых ошибках

Технические характеристики:
    - Алгоритм: bcrypt (реализация python-bcrypt)
    - Формат хеша: $2b$[cost]$[22-символьная соль][31-символьный хеш]
    - Кодировка: UTF-8 для всех строковых операций
    - Ограничение длины: обрезка паролей до 72 байт (ограничение bcrypt)

Принципы безопасности:
    - Каждый пароль хешируется с уникальной солью
    - Ошибки валидации не раскрывают информацию о системе
    - Невозможно восстановить исходный пароль из хеша
    - Защита от атак по времени через константное время проверки
"""

import bcrypt


def get_password_hash(password: str) -> str:
    """
    Хеширует пароль с использованием алгоритма bcrypt.

    Args:
        password (str): Пароль в открытом виде для хеширования.
                       Если передан None, преобразуется в пустую строку.

    Returns:
        str: Хешированный пароль в виде строки UTF-8.

    Примечания:
        - bcrypt накладывает ограничение в 72 байта на длину пароля.
          Пароли длиннее 72 байт обрезаются до допустимой длины.
        - Соль генерируется автоматически с параметрами по умолчанию.
        - Результат содержит всю информацию для верификации (соль + хеш).
    """
    if password is None:
        password = ""

    # Обрезка до 72 байт (техническое ограничение bcrypt)
    if len(password.encode("utf-8")) > 72:
        password = password[:72]

    # Генерация соли и создание хеша
    salt: bytes = bcrypt.gensalt()
    hashed: bytes = bcrypt.hashpw(password.encode("utf-8"), salt)

    return hashed.decode("utf-8")


def verify_password(plain_password: str, hashed_password: str) -> bool:
    """
    Проверяет соответствие открытого пароля его хешированной версии.

    Args:
        plain_password (str): Пароль в открытом виде для проверки.
        hashed_password (str): Хеш пароля, полученный от get_password_hash().

    Returns:
        bool: True - пароль соответствует хешу, False - не соответствует
              или произошла ошибка валидации.

    Примечания:
        - Возвращает False при любых ошибках (принцип безопасного отказа)
        - Проверяет корректность формата хеша (префикс "$2")
        - Обрабатывает исключения ValueError без раскрытия деталей
        - Работает за константное время для защиты от атак по времени
    """
    # Валидация входных данных
    if plain_password is None:
        return False

    # Проверка формата хеша (должен начинаться с префикса bcrypt)
    if not hashed_password or not hashed_password.startswith("$2"):
        return False

    # Сравнение пароля с хешем
    try:
        result: bool = bcrypt.checkpw(plain_password.encode("utf-8"), hashed_password.encode("utf-8"))
        return result
    except ValueError:
        # Безопасное возвращение False при ошибках
        return False
