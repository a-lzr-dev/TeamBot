"""
Утилиты для работы со временем и датами.

Назначение:
    Предоставляет вспомогательные функции для работы с временными метками
    и датами в приложении.

Основные функции:
    1. Получение текущего времени в ISO формате с часовым поясом UTC
    2. (В будущем) Дополнительные утилиты для работы со временем

Технические особенности:
    - Использует единую функцию datetime_now() из моделей
    - Возвращает время в ISO 8601 формате с суффиксом Z (UTC)
    - Подходит для использования в API и JSON сериализации

Архитектура:
    - Простой модуль с утилитами
    - Может быть расширен дополнительными функциями
"""

from ..models import datetime_now

# ============================================================
# 1. УТИЛИТЫ ДЛЯ РАБОТЫ СО ВРЕМЕНЕМ
# ============================================================


def get_timestamp() -> str:
    """
    Получение текущего времени в ISO формате с часовым поясом UTC.

    Использует единую функцию datetime_now() из модуля models,
    которая возвращает текущее время с учётом часового пояса.

    Returns:
        str: Текущее время в формате ISO 8601 с суффиксом Z (UTC)

    Пример:
        >>> get_timestamp()
        '2024-01-15T14:30:45.123456Z'
    """
    dt = datetime_now()
    return dt.isoformat() + "Z"


